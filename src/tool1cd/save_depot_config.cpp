// 16 hex-символов с нулевым выравниванием — поле заголовка блока
static void cf16_hex16(char *dst, uint64_t value)
{
	static const char digits[] = "0123456789abcdef";
	for(int i = 0; i < 16; i++)
	{
		dst[i] = digits[(value >> ((15 - i) * 4)) & 0xF];
	}
}

// Один блок документа: 55-байтный заголовок + данные + добивка нулями
// до страницы (512 — минимальная страница, как у конфигуратора).
static void cf16_write_block(TStream *out, TStream *data, int64_t len, const string &what)
{
	const int64_t page = len > 512 ? len : 512;
	char header[55];
	header[0] = '\r';
	header[1] = '\n';
	cf16_hex16(header + 2, (uint64_t)len);
	header[18] = ' ';
	cf16_hex16(header + 19, (uint64_t)page);
	header[35] = ' ';
	cf16_hex16(header + 36, CF16_UNDEFINED);
	header[52] = ' ';
	header[53] = '\r';
	header[54] = '\n';
	out->WriteBuffer(header, sizeof(header));

	vector<char> buffer(4 << 20);
	data->Seek(0, soFromBeginning);
	int64_t left = len;
	while(left > 0)
	{
		int64_t chunk = left < (int64_t)buffer.size() ? left : (int64_t)buffer.size();
		if(data->Read(buffer.data(), chunk) < chunk)
		{
			throw Exception("Короткое чтение потока при записи cf: " + what);
		}
		out->WriteBuffer(buffer.data(), chunk);
		left -= chunk;
	}
	if(page > len)
	{
		vector<char> zeros((size_t)(page - len), 0);
		out->WriteBuffer(zeros.data(), zeros.size());
	}
}

// Элемент контейнера: заголовочный блок (время x2, ноль, имя UTF-16, ноль)
// и блок данных; адреса блоков уходят в FAT.
static void cf16_add_elem(TStream *out, TStream *fat, const string &name, TStream *data)
{
	TMemoryStream header_stream;
	int32_t four_byte_zero = 0;
	V8Time now = V8Time::current_time();
	now.write_to_stream(&header_stream);
	now.write_to_stream(&header_stream);
	header_stream.Write(&four_byte_zero, 4);
	auto wide_name = SysUtils::TEncoding::Unicode->fromUtf8(name);
	header_stream.Write(wide_name.data(), wide_name.size());
	header_stream.Write(&four_byte_zero, 4);

	const int64_t header_addr = out->GetSize() - CF16_BASE_OFFSET;
	cf16_write_block(out, &header_stream, header_stream.GetSize(), "заголовок " + name);
	const int64_t data_addr = out->GetSize() - CF16_BASE_OFFSET;
	cf16_write_block(out, data, data->GetSize(), "данные " + name);

	uint64_t addresses[3] = {(uint64_t)header_addr, (uint64_t)data_addr, CF16_UNDEFINED};
	fat->WriteBuffer(addresses, sizeof(addresses));
}

// Запись конфигурации в формате конфигуратора 8.3.16. Элементы extmap уже
// сжаты (как в классическом пути); для старых хранилищ вложенный классический
// каталог metadata собирается существующим V8Catalog и ложится одним сжатым
// элементом. Потоки элементов удаляются здесь, как в классическом пути.
static void save_depot_config_format16(const boost::filesystem::path &filepath,
									   map<string, TStream *> &extmap,
									   map<string, TStream *> &metamap,
									   bool oldformat)
{
	TFileStream out(filepath.string(), fmCreate);
	out.WriteBuffer(CF16_STUB, sizeof(CF16_STUB));

	const int64_t elem_count = (int64_t)extmap.size() + (oldformat ? 1 : 0);
	const int64_t toc_size = 24 * elem_count;
	const int64_t toc_reserve = toc_size > 0x10000 ? toc_size : 0x10000;
	{
		vector<char> zeros((size_t)(20 + 55 + toc_reserve), 0);
		out.WriteBuffer(zeros.data(), zeros.size());
	}

	TMemoryStream fat;
	if(oldformat)
	{
		TTempStream *meta_stream = new TTempStream;
		{
			// Вложенный каталог остаётся классическим: его читатель — сама
			// платформа, и только корневая обвязка меняется на 8.3.16.
			V8Catalog metadata_catalog(meta_stream, false, true);
			for(auto &psmap : metamap)
			{
				metadata_catalog.createFile(psmap.first)->write_and_close(psmap.second);
				delete psmap.second;
				psmap.second = nullptr;
			}
		}
		TTempStream *packed = new TTempStream;
		meta_stream->Seek(0, soFromBeginning);
		ZDeflateStream(meta_stream, packed);
		delete meta_stream;
		cf16_add_elem(&out, &fat, "metadata", packed);
		delete packed;
	}
	for(auto &psmap : extmap)
	{
		cf16_add_elem(&out, &fat, psmap.first, psmap.second);
		delete psmap.second;
		psmap.second = nullptr;
	}

	const int64_t free_addr = out.GetSize() - CF16_BASE_OFFSET;
	out.Seek(CF16_BASE_OFFSET, soFromBeginning);
	const uint64_t free_value = (uint64_t)free_addr;
	const uint32_t page_size = 512;
	const uint32_t storage_version = 0;
	const uint32_t reserved = 0;
	out.WriteBuffer(&free_value, 8);
	out.WriteBuffer(&page_size, 4);
	out.WriteBuffer(&storage_version, 4);
	out.WriteBuffer(&reserved, 4);
	cf16_write_block(&out, &fat, fat.GetSize(), "оглавление");
}

/* возвращает текст вида
{
{216,0}
}*/
string serialize_version(int configVerMajor, int configVerMinor)
{
	auto t = std::make_shared<Tree>("", node_type::nd_list, nullptr);
	auto tc = new Tree("", node_type::nd_list, t.get());
	tc = new Tree("", node_type::nd_list, tc);
	tc->add_child(to_string(configVerMajor), node_type::nd_number);
	tc->add_child(to_string(configVerMinor), node_type::nd_number);
	return outtext(t.get());
}

